func writeRepoFile(t *testing.T, root, rel, content string) {
	t.Helper()
	full := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func gitInit(t *testing.T, root string) {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not available")
	}
	if out, err := exec.Command("git", "-C", root, "init", "-q").CombinedOutput(); err != nil {
		t.Fatalf("git init: %v: %s", err, out)
	}
}

func TestClassifyEnryOnly(t *testing.T) {
	root := t.TempDir()
	writeRepoFile(t, root, "package-lock.json", "{}\n")
	writeRepoFile(t, root, "vendor/foo.go", "package foo\n")
	writeRepoFile(t, root, "main.go", "package main\n")
	writeRepoFile(t, root, "gen.go", "// Code generated by x. DO NOT EDIT.\n\npackage gen\n")

	files := []vcs.FileChange{
		{Path: "package-lock.json", Status: "A"},
		{Path: "vendor/foo.go", Status: "A"},
		{Path: "main.go", Status: "A"},
		{Path: "gen.go", Status: "A"},
		{Path: "vendor/gone.go", Status: "D"},
	}
	got := Classify(context.Background(), root, files)

	cases := []struct {
		path      string
		generated bool
		vendored  bool
	}{
		{"package-lock.json", true, false},
		{"vendor/foo.go", false, true},
		{"main.go", false, false},
		{"gen.go", true, false},
	}
	for _, tc := range cases {
		t.Run(tc.path, func(t *testing.T) {
			f := got[tc.path]
			if f.Generated != tc.generated || f.Vendored != tc.vendored {
				t.Errorf("Classify(%q) = %+v, want generated=%v vendored=%v", tc.path, f, tc.generated, tc.vendored)
			}
		})
	}
	t.Run("deleted file is skipped", func(t *testing.T) {
		if _, ok := got["vendor/gone.go"]; ok {
			t.Errorf("deleted path classified, want it skipped: %+v", got["vendor/gone.go"])
		}
	})
}

func TestClassifyCheckAttrOverride(t *testing.T) {
	root := t.TempDir()
	gitInit(t, root)
	writeRepoFile(t, root, ".gitattributes", "weird.txt linguist-generated=true\ncool.pb.go linguist-generated=false\n")
	writeRepoFile(t, root, "weird.txt", "just plain text\n")
	writeRepoFile(t, root, "cool.pb.go", "package cool\n")

	files := []vcs.FileChange{
		{Path: "weird.txt", Status: "A"},
		{Path: "cool.pb.go", Status: "A"},
	}
	got := Classify(context.Background(), root, files)

	t.Run("override up: mark forces Generated on a plain file", func(t *testing.T) {
		if !got["weird.txt"].Generated {
			t.Errorf("weird.txt = %+v, want Generated=true from linguist-generated=true", got["weird.txt"])
		}
	})
	t.Run("override down: mark forces Generated off despite enry", func(t *testing.T) {
		if got["cool.pb.go"].Generated {
			t.Errorf("cool.pb.go = %+v, want Generated=false from linguist-generated=false (beats enry's .pb.go rule)", got["cool.pb.go"])
		}
	})
}

func TestClassifyJJPureSkipsOverlay(t *testing.T) {
	root := t.TempDir()
	// .gitattributes present but no .git: the overlay gate (os.Stat .git) fails,
	// so the manual mark is not honored and enry's verdict (false) stands.
	writeRepoFile(t, root, ".gitattributes", "weird.txt linguist-generated=true\n")
	writeRepoFile(t, root, "weird.txt", "just plain text\n")

	got := Classify(context.Background(), root, []vcs.FileChange{{Path: "weird.txt", Status: "A"}})
	if got["weird.txt"].Generated {
		t.Errorf("weird.txt = %+v, want Generated=false (no .git, mark skipped)", got["weird.txt"])
	}
}

func TestParseCheckAttr(t *testing.T) {
	out := []byte("weird.txt\x00linguist-generated\x00set\x00" +
		"weird.txt\x00linguist-vendored\x00unspecified\x00" +
		"cool.pb.go\x00linguist-generated\x00unset\x00" +
		"lib.js\x00linguist-vendored\x00true\x00")

	got := parseCheckAttr(out)
	want := map[string]fileAttrs{
		"weird.txt":  {generated: attrSet, vendored: attrUnspecified},
		"cool.pb.go": {generated: attrUnset, vendored: attrUnspecified},
		"lib.js":     {generated: attrUnspecified, vendored: attrSet},
	}
	if len(got) != len(want) {
		t.Fatalf("parseCheckAttr returned %d paths, want %d: %+v", len(got), len(want), got)
	}
	for path, w := range want {
		if got[path] != w {
			t.Errorf("parseCheckAttr[%q] = %+v, want %+v", path, got[path], w)
		}
	}
}
